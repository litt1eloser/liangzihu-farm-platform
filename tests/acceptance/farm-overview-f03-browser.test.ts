import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {chromium} from 'playwright';
import {withDb} from '../support/db';
import {withApp} from '../support/app';
import {actorFixture,objectFixture,permit} from '../support/fixtures';

test('F03 测点当前值事实展示、局部状态与相关记录告警',{timeout:180000},()=>withDb(async pool=>{
 const owner=await actorFixture(pool,'owner');
 const farm=await objectFixture(pool,owner.id),pond=await objectFixture(pool,owner.id),facility=await objectFixture(pool,owner.id);
 await pool.query("UPDATE objects SET parent_id=$2,name='南塘口',code='F03-P',kind='pond',boundary_status='verified',boundary=ST_GeomFromText('POLYGON((114.62 30.24,114.63 30.24,114.63 30.25,114.62 30.25,114.62 30.24))',4326) WHERE id=$1",[pond,farm]);
 await pool.query("UPDATE objects SET parent_id=$2,name='测点房',code='F03-F',kind='facility',boundary_status='draft',boundary=ST_GeomFromText('POINT(114.635 30.255)',4326) WHERE id=$1",[facility,farm]);
 await permit(pool,owner.id,farm,['read','configure']);await permit(pool,owner.id,pond,['read','configure']);await permit(pool,owner.id,facility,['read','configure']);
 const source=(await pool.query("INSERT INTO data_sources(object_id,code,name,provider,verified,created_by) VALUES($1,'F03-SRC','F03 合成来源','synthetic',true,$2) RETURNING id",[pond,owner.id])).rows[0].id;
 const device=(await pool.query("INSERT INTO devices(object_id,source_id,external_id,name,kind,verified,source,created_by) VALUES($1,$2,'F03-D1','F03 水质仪','physical',true,'仅测试',$3) RETURNING id",[pond,source,owner.id])).rows[0].id;
 const pointDo=(await pool.query("INSERT INTO points(device_id,code,name,metric,unit,created_by) VALUES($1,'F03-DO','溶解氧','dissolved_oxygen','mg/L',$2) RETURNING id",[device,owner.id])).rows[0].id;
 const pointWt=(await pool.query("INSERT INTO points(device_id,code,name,metric,unit,created_by) VALUES($1,'F03-WT','水温','water_temp','°C',$2) RETURNING id",[device,owner.id])).rows[0].id;
 const bindingDo=(await pool.query("INSERT INTO point_bindings(point_id,object_id,valid_from,verified,evidence,created_by) VALUES($1,$2,'2026-09-01',true,'仅测试绑定',$3) RETURNING id",[pointDo,pond,owner.id])).rows[0].id;
 await pool.query("INSERT INTO point_bindings(point_id,object_id,valid_from,verified,evidence,created_by) VALUES($1,$2,'2026-09-01',true,'仅测试绑定',$3)",[pointWt,pond,owner.id]);
 const raw=(await pool.query("INSERT INTO raw_receipts(source_id,received_at,body,sha256,synthetic) VALUES($1,now(),'{}',repeat('a',64),true) RETURNING id",[source])).rows[0].id;
 const head=(await pool.query("INSERT INTO observation_heads(identity_hash,point_id) VALUES(repeat('b',64),$1) RETURNING id",[pointDo])).rows[0].id;
 const obs=(await pool.query("INSERT INTO observations(head_id,content_hash,source_id,external_device_id,point_id,object_id,binding_id,metric,sampled_at,received_at,raw_value,value,unit,quality,reasons,origin,raw_ref) VALUES($1,repeat('c',64),$2,'F03-D1',$3,$4,$5,'dissolved_oxygen',now()-interval '2 minutes',now(),'6.1',6.1,'mg/L','valid','{}','live',$6) RETURNING id",[head,source,pointDo,pond,bindingDo,raw])).rows[0].id;
 await pool.query("INSERT INTO point_current(point_id,observation_id,sampled_at,quality,reasons) VALUES($1,$2,now()-interval '2 minutes','valid','{}')",[pointDo,obs]);
 await pool.query("INSERT INTO alerts(object_id,correlation_key,kind,title,severity,state,opened_at) VALUES($1,'F03-AL-1','measurement','溶氧偏低','warning','open',now()-interval '1 hour')",[pond]);
 await pool.query("INSERT INTO alerts(object_id,correlation_key,kind,title,severity,state,opened_at,recovered_at) VALUES($1,'F03-AL-2','monitoring_gap','监测曾中断','info','recovered',now()-interval '2 days',now()-interval '1 day')",[pond]);
 await withApp(pool,async app=>{
  const browser=await chromium.launch(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH}:{});
  try{
   const context=await browser.newContext({viewport:{width:1440,height:900},locale:'zh-CN'});
   await context.addCookies([{name:'agri_session',value:await app.authenticate(owner),url:app.origin}]);
   const page=await context.newPage(),errors:string[]=[];
   page.on('pageerror',error=>errors.push(error.message));
   await mkdir('docs/acceptance/m2f03',{recursive:true});
   const detail=page.getByRole('complementary',{name:'对象详情'});
   await page.goto(app.origin+'/farm-overview');
   await page.getByRole('button',{name:'南塘口',exact:true}).waitFor();
   await page.getByRole('button',{name:'南塘口',exact:true}).click();
   await detail.getByRole('heading',{name:'南塘口'}).waitFor();
   await detail.getByRole('button',{name:'查看详细资料'}).click();
   await detail.getByRole('tab',{name:'水体监测',exact:true}).click();
   await detail.getByText('溶解氧',{exact:true}).waitFor();
   await detail.getByText('尚未核实：缺少时效依据').waitFor();
   await detail.getByText(/尚未核实：暂无可用当前值/).waitFor();
   await page.screenshot({path:'docs/acceptance/m2f03/01-水体监测当前值.png'});
   await detail.getByRole('tab',{name:'相关记录',exact:true}).click();
   await detail.getByText('溶氧偏低',{exact:true}).waitFor();
   await detail.getByText('警告 · 当前',{exact:true}).waitFor();
   await detail.getByText('提示 · 已恢复',{exact:true}).waitFor();
   await detail.getByRole('button',{name:'养殖',exact:true}).click();
   await detail.getByText(/该类别记录暂未接入查询/).waitFor();
   await page.screenshot({path:'docs/acceptance/m2f03/02-相关记录告警.png'});
   await page.getByRole('button',{name:'测点房',exact:true}).click();
   await detail.getByRole('heading',{name:'测点房'}).waitFor();
   await detail.getByRole('button',{name:'查看详细资料'}).click();
   await detail.getByRole('tab',{name:'关联设备',exact:true}).click();
   await detail.getByText(/暂无关联测点。/).waitFor();
   assert.deepEqual(errors,[],'页面不得出现脚本错误');
   await context.close();
  }finally{await browser.close();}
 });
}));
